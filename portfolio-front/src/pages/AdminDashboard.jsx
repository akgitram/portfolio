const emptyObject = (resource) =>
  Object.fromEntries(
    resource.fields.map((field) => [
      field.name,
      field.type === "checkbox" ? false : "",
    ]),
  );

function getRows(data) {
  if (Array.isArray(data)) return data;
  if (Array.isArray(data?.content)) return data.content;
  if (Array.isArray(data?.data)) return data.data;
  if (Array.isArray(data?.items)) return data.items;
  return [];
}

function getErrorMessage(error, fallback) {
  const data = error?.response?.data;

  if (typeof data === "string" && data.trim()) return data;
  const message = data?.message || data?.error || error?.message || fallback;
  const status = error?.response?.status;
  return status ? `${message} (HTTP ${status})` : message;
}

function preparePayload(form, resource) {
  const payload = {};

  resource.fields.forEach((field) => {
    const value = form[field.name];

    if (
      resource.endpoint === "/experiences" &&
      form.current &&
      field.name === "endDate"
    ) {
      payload.endDate = null;
    } else if (field.type === "number") {
      payload[field.name] =
        value === "" || value == null ? null : Number(value);
    } else if (field.type === "date") {
      // Send null for an optional empty date (e.g. endDate for a current job).
      payload[field.name] = value === "" || value == null ? null : value;
    } else if (field.type === "checkbox") {
      payload[field.name] = Boolean(value);
    } else if (typeof value === "string") {
      // Trim accidental whitespace while keeping blank fields as empty strings.
      payload[field.name] = value.trim();
    } else {
      payload[field.name] = value;
    }
  });

  return payload;
}

function displayValue(value) {
  if (value === null || value === undefined || value === "") return "—";
  if (typeof value === "boolean") return value ? "Yes" : "No";
  if (Array.isArray(value)) return value.join(", ");
  if (typeof value === "object") return JSON.stringify(value);
  return String(value);
}

function getAllRecordColumns(rows) {
  // Show every property returned by the database API, including fields not listed in the form.
  const keys = new Set(["id"]);
  rows.forEach((record) => {
    Object.keys(record || {}).forEach((key) => keys.add(key));
  });
  return [...keys];
}

